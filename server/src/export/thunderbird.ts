import { zipSync, strToU8 } from 'fflate';
import QRCode from 'qrcode';
import type { Security } from '../providers.js';
import { type ExportAccount, type ExportFile } from './common.js';

/* Thunderbird's nsMsgSocketType and nsMsgAuthMethod values. */
const SOCKET_TYPE: Record<Security, number> = { none: 0, starttls: 2, tls: 3 };
const AUTH_NONE = 1;
const AUTH_PASSWORD_CLEARTEXT = 3;
const AUTH_OAUTH2 = 10;

const pref = (name: string, value: string | number | boolean) =>
  `user_pref(${JSON.stringify(name)}, ${typeof value === 'string' ? JSON.stringify(value) : String(value)});`;

/**
 * prefs.js entries describing the accounts, in the layout Thunderbird itself writes.
 * Mail directories are deliberately omitted: Thunderbird's profile importer then gives
 * every imported server its own new, unique folder.
 */
export function thunderbirdPrefs(accounts: ExportAccount[]): string {
  const lines: string[] = [
    '// Mozilla User Preferences',
    '',
    '// Generated by HomeMail. Import it in Thunderbird with',
    '// Tools > Import > Import from another Thunderbird installation > choose the .zip file.',
    '',
  ];
  const keys = accounts.map((_, i) => i + 1);
  lines.push(pref('mail.accountmanager.accounts', keys.map((n) => `account${n}`).join(',')));
  lines.push(pref('mail.smtpservers', keys.map((n) => `smtp${n}`).join(',')));
  accounts.forEach((a, i) => {
    const n = i + 1;
    const oauth = a.authType === 'oauth2';
    const server = `mail.server.server${n}.`;
    const smtp = `mail.smtpserver.smtp${n}.`;
    const ident = `mail.identity.id${n}.`;
    lines.push(
      '',
      pref(`mail.account.account${n}.identities`, `id${n}`),
      pref(`mail.account.account${n}.server`, `server${n}`),
      pref(`${ident}fullName`, a.displayName),
      pref(`${ident}useremail`, a.email),
      pref(`${ident}smtpServer`, `smtp${n}`),
      pref(`${ident}valid`, true),
      // Providers like Gmail file sent mail themselves; another copy would duplicate it.
      pref(`${ident}fcc`, !(a.providerSavesSent && a.protocol === 'imap')),
      pref(`${server}type`, a.protocol),
      pref(`${server}hostname`, a.incoming.host),
      pref(`${server}port`, a.incoming.port),
      pref(`${server}socketType`, SOCKET_TYPE[a.incoming.security]),
      pref(`${server}userName`, a.incoming.username),
      pref(`${server}authMethod`, oauth ? AUTH_OAUTH2 : AUTH_PASSWORD_CLEARTEXT),
      pref(`${server}name`, a.label),
      pref(`${server}login_at_startup`, true),
      pref(`${server}check_new_mail`, true),
      pref(`${smtp}hostname`, a.smtp.host),
      pref(`${smtp}port`, a.smtp.port),
      pref(`${smtp}try_ssl`, SOCKET_TYPE[a.smtp.security]),
      pref(`${smtp}username`, a.smtp.username),
      pref(`${smtp}authMethod`, !a.smtp.username ? AUTH_NONE : oauth ? AUTH_OAUTH2 : AUTH_PASSWORD_CLEARTEXT),
      pref(`${smtp}description`, a.label),
    );
    if (a.protocol === 'pop3') lines.push(pref(`${server}leave_on_server`, a.leaveOnServer));
    if (a.signature.trim()) {
      lines.push(pref(`${ident}htmlSigText`, a.signature), pref(`${ident}htmlSigFormat`, false), pref(`${ident}attach_signature`, false));
    }
  });
  return lines.join('\n') + '\n';
}

export function exportThunderbird(accounts: ExportAccount[]): ExportFile {
  const readme = `HomeMail export for Thunderbird (desktop)

How to import
1. In Thunderbird open the menu > Tools > Import (or the "Import" button in the account hub).
2. Choose "Import from another Thunderbird installation".
3. Choose "Select a profile folder or zip file" and pick this .zip file.
4. Keep "Accounts and settings" ticked and start the import. Restart Thunderbird if asked.

Passwords are not included. Thunderbird asks for each password the first time it connects.
Accounts set up with Google or Microsoft sign-in open the provider's sign-in window instead.
Servers with self-signed certificates (e.g. Proton Mail Bridge) ask you to confirm a security exception.

Accounts in this file:
${accounts.map((a) => `- ${a.label} <${a.email}> (${a.protocol.toUpperCase()} ${a.incoming.host})`).join('\n')}
`;
  const zip = zipSync({ 'prefs.js': strToU8(thunderbirdPrefs(accounts)), 'README.txt': strToU8(readme) });
  return { filename: 'homemail-thunderbird-import.zip', contentType: 'application/zip', body: Buffer.from(zip), skipped: [] };
}

/* ---------- Thunderbird for Android: "Import from Thunderbird desktop" QR codes ---------- */

/** Same payload Thunderbird desktop's "Export for Mobile" produces (format version 1). */
const QR_FORMAT_VERSION = 1;
const ACCOUNTS_PER_QR_CODE = 3;
const QR_AUTH: Record<string, number> = { none: 0, password: 1, oauth2: 6 };

export interface QrCodeImage {
  part: number;
  count: number;
  dataUrl: string;
  accounts: string[];
}

function qrAccount(a: ExportAccount): unknown[] {
  const auth = QR_AUTH[a.authType];
  const incoming = [a.protocol === 'imap' ? 0 : 1, a.incoming.host, a.incoming.port, SOCKET_TYPE[a.incoming.security], auth, a.incoming.username, a.label, a.password ?? ''];
  const outgoing = [0, a.smtp.host, a.smtp.port, SOCKET_TYPE[a.smtp.security], a.smtp.username ? auth : QR_AUTH.none, a.smtp.username, a.smtpPassword ?? a.password ?? ''];
  // An account's outgoing list holds groups of [server, ...identities].
  return [incoming, [[outgoing, [a.email, a.displayName]]]];
}

const singleLine = (s: string) => s.replace(/[\r\n]+/g, ' ');

export async function thunderbirdQrCodes(accounts: ExportAccount[]): Promise<{ codes: QrCodeImage[]; skipped: ExportFile['skipped'] }> {
  const skipped: ExportFile['skipped'] = [];
  const usable = accounts
    .filter((a) => {
      // The Android app rejects values containing line breaks.
      if ([a.password, a.smtpPassword].some((p) => p && /[\r\n]/.test(p))) {
        skipped.push({ label: a.label, reason: 'Password contains a line break, which the QR format cannot carry.' });
        return false;
      }
      return true;
    })
    .map((a) => ({ ...a, label: singleLine(a.label), displayName: singleLine(a.displayName) }));
  const count = Math.ceil(usable.length / ACCOUNTS_PER_QR_CODE);
  const codes: QrCodeImage[] = [];
  for (let i = 0; i < count; i++) {
    const chunk = usable.slice(i * ACCOUNTS_PER_QR_CODE, (i + 1) * ACCOUNTS_PER_QR_CODE);
    const payload = JSON.stringify([QR_FORMAT_VERSION, [i + 1, count], ...chunk.flatMap(qrAccount)]);
    const dataUrl = await QRCode.toDataURL(payload, { errorCorrectionLevel: 'L', margin: 2, scale: 6 });
    codes.push({ part: i + 1, count, dataUrl, accounts: chunk.map((a) => a.label) });
  }
  return { codes, skipped };
}
